test('MI_INDEX', () => {
  const m = parseMiIndex(MI);
  assert.equal(m.close, 44257.15); assert.equal(m.change, 1545.23); assert.equal(m.pct, 3.62);
  assert.equal(m.turnover, 8491.65);
  assert.deepEqual(m.breadth, { up: 642, upLimit: 25, down: 374, downLimit: 1, flat: 90 });
  assert.deepEqual(m.sectors.map(s => s[0]), ['水泥','食品','半導體']);
  assert.equal(m.sectors[1][2], -0.95);
  assert.equal(m.topGain[0][1], '競國'); assert.equal(m.topGain[0][3], 10);
  assert.equal(m.topLoss[0][1], '台揚'); assert.equal(m.topLoss[0][3], -10);
  assert.ok(!m.topValue.some(r => r[0] === '0050'));
  assert.equal(m.topValue[0][1], '台積電');
});
